rows = []
page_num = [1]

def add_text_page(label, content):
    rows.append({
        'ページ番号': page_num[0],
        '使用するコマ割りテンプレ': 'テキストページ',
        '漫画作成のプロンプト': make_text_page_prompt(label, content),
        'コマ別テキストJSON': json.dumps([], ensure_ascii=False),
    })
    page_num[0] += 1

def add_manga_page(template, panel_items, scene_desc, outfit=''):
    """コマ別テキストJSONと一緒にページを追加"""
    prompt = make_prompt(template, scene_desc, panel_items, outfit)
    rows.append({
        'ページ番号': page_num[0],
        '使用するコマ割りテンプレ': template,
        '漫画作成のプロンプト': prompt,
        'コマ別テキストJSON': json.dumps(panel_items, ensure_ascii=False),
    })
    page_num[0] += 1

def nar(panel_id, text):
    return {'panel_id': panel_id, 'type': 'narration', 'speaker': None, 'text': text}

def dlg(panel_id, speaker, text):
    return {'panel_id': panel_id, 'type': 'dialogue', 'speaker': speaker, 'text': text}

