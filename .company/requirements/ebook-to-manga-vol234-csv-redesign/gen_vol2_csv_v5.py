def split_text_30(text, max_len=30):
    """テキストを30字以内のチャンクに分割する（句読点・接続詞を考慮）"""
    if len(text) <= max_len:
        return [text]

    chunks = []
    # 句読点で分割を試みる
    separators = ['。', '！', '？', '——', '──', '…', '、']

    remaining = text
    while len(remaining) > max_len:
        # max_len以内で最後の句読点を探す
        best_pos = -1
        for sep in separators:
            pos = remaining[:max_len].rfind(sep)
            if pos > best_pos and pos > 0:
                best_pos = pos + len(sep)

        if best_pos > 5:  # 5字以上の意味あるチャンク
            chunks.append(remaining[:best_pos])
            remaining = remaining[best_pos:]
        else:
            # 句読点がなければmax_lenで強制分割（自然な区切りを探す）
            # スペースや助詞の後を探す
            cut_pos = max_len
            # 少し手前から自然な区切りを探す
            for i in range(max_len, max(5, max_len-10), -1):
                if i < len(remaining) and remaining[i] in ['に', 'は', 'を', 'が', 'の', 'で', 'と', 'も', 'へ', 'て', 'し']:
                    cut_pos = i + 1
                    break
            chunks.append(remaining[:cut_pos])
            remaining = remaining[cut_pos:]

    if remaining:
        chunks.append(remaining)

    return [c for c in chunks if c.strip()]

def make_prompt(template, scene_desc, panel_items, outfit=''):
    """プロンプト文字列を生成"""
    layout = TEMPLATE_LAYOUTS.get(template, f'{template}')
    outfit_line = f'◆【補足情報】服装: {outfit}' if outfit else ''

    story_lines = []
    panel_pos_map = {
        'テンプレ1': {1: 'ページ全体'},
        'テンプレ2': {1: '上段', 2: '下段'},
        'テンプレ3': {1: '上・小', 2: '下・大'},
        'テンプレ4': {1: '左', 2: '右'},
        'テンプレ5': {1: '上段', 2: '中段', 3: '下段'},
        'テンプレ6': {1: '上・大', 2: '下左・小', 3: '下右・小'},
        'テンプレ7': {1: '上左・小', 2: '上右・小', 3: '下・大'},
    }
    pos_map = panel_pos_map.get(template, {})

    # panelごとにグループ化
    from collections import defaultdict
    panel_groups = defaultdict(list)
    for item in panel_items:
        panel_groups[item['panel_id']].append(item)

    for pid in sorted(panel_groups.keys()):
        pos_label = pos_map.get(pid, f'{pid}コマ目')
        items = panel_groups[pid]

        scene = scene_desc.get(pid, '')
        dialogues = [i for i in items if i['type'] == 'dialogue']
        narrations = [i for i in items if i['type'] == 'narration']

        # セリフ
        if dialogues:
            serif_parts = [f'【{d["speaker"]}】{d["text"]}' for d in dialogues]
            serif_str = ' / '.join(serif_parts)
        else:
            serif_str = 'なし'

        # ナレーション
        if narrations:
            nar_parts = [f'［四角枠］{n["text"]}' for n in narrations]
            nar_str = ' '.join(nar_parts)
        else:
            nar_str = 'なし'

        story_lines.append(f'{pid}コマ目 ({pos_label}): {scene} セリフ: {serif_str} ナレーション: {nar_str} オノマトペ: なし')

    parts = [COMMON_HEADER]
    if outfit_line:
        parts.append(outfit_line)
    parts.append(f'◆【コマ構成】{layout}')
    parts.append('◆【ストーリー】')
    parts.extend(story_lines)

    return '\n'.join(parts)

def make_text_page_prompt(label, content):
    return f'◆【テキストページ】このページは画像生成不要。EPUB製本時にテキストとして直接レンダリングする。\n◆【{label}】\n{content}'

