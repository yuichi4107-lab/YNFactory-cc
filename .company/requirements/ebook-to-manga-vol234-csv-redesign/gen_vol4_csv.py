def char(names):
    defs = []
    if "ミサキ" in names: defs.append(MISAKI_DEF)
    if "ケンタ" in names: defs.append(KENTA_DEF)
    if "ひなた" in names: defs.append(HINATA_DEF)
    if "タクヤ" in names: defs.append(TAKUYA_DEF)
    return "◆【絶対最優先】キャラクター外見: " + ", ".join(defs)

def outfit(names, misaki_pajama=False):
    outfits = []
    if "ミサキ" in names:
        outfits.append(MISAKI_PAJAMA if misaki_pajama else MISAKI_OUTFIT)
    if "ケンタ" in names: outfits.append(KENTA_OUTFIT)
    if "ひなた" in names: outfits.append(HINATA_OUTFIT)
    if "タクヤ" in names: outfits.append(TAKUYA_OUTFIT)
    return "◆【補足情報】服装: " + " / ".join(outfits)

def tmpl_prompt(n):
    templates = {
        1: "テンプレ1: ページ全体1コマ",
        2: "テンプレ2: 上下均等2分割",
        3: "テンプレ3: 上段小→下段大",
        4: "テンプレ4: 上段大→下段小",
        5: "テンプレ5: 上・中・下3段",
        6: "テンプレ6: 上段1コマ + 下段左右2コマ",
        7: "テンプレ7: 上段左右2コマ + 下段1コマ",
    }
    return f"◆【コマ構成】{templates[n]}"

def build_prompt(tmpl_n, char_names, story_lines, misaki_pajama=False, extra_info=None):
    parts = [BASE]
    parts.append(char(char_names))
    parts.append(SIZE)
    parts.append(MARGIN)
    parts.append(outfit(char_names, misaki_pajama))
    if extra_info:
        parts.append(extra_info)
    parts.append(tmpl_prompt(tmpl_n))
    parts.append(STYLE)
    parts.append("◆【ストーリー】")
    parts.extend(story_lines)
    return "\n".join(parts)

def j(items):
    return json.dumps(items, ensure_ascii=False)

def dlg(panel_id, speaker, text):
    return {"panel_id": panel_id, "type": "dialogue", "speaker": speaker, "text": text}

def nar(panel_id, text):
    return {"panel_id": panel_id, "type": "narration", "speaker": None, "text": text}

