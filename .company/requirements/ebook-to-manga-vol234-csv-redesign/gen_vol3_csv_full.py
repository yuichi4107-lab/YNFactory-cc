def d(pid, spk, txt): return {"panel_id": pid, "type": "dialogue", "speaker": spk, "text": txt}
def n(pid, txt): return {"panel_id": pid, "type": "narration", "speaker": None, "text": txt}

def build_prompt(chars, costumes, tmpl_num, story_lines, extra_notes=None):
    parts = common_header(chars, costumes, extra_notes)
    parts.append(TMPL[tmpl_num])
    parts.append(ART)
    parts.append("◆【ストーリー】")
    parts.extend(story_lines)
    return "\n".join(parts)

def jdump(items):
    return json.dumps(items, ensure_ascii=False, separators=(',', ':'))

