def common_header(chars, costumes=None, extra_notes=None):
    lines = [
        "◆【注意】【】で囲まれた単語は感情や状況の指示であり、画像内に文字として描画しないでください",
        "◆【絶対最優先】必ずフルカラーにしてください",
        "◆【絶対最優先】必ず日本のアニメ・マンガ調のイラストで描いてください。実写風・フォトリアル風は禁止です。",
    ]
    if chars:
        lines.append(f"◆【絶対最優先】キャラクター外見: {', '.join(chars)}")
    lines.append("◆【出力サイズ】2:3")
    lines.append("◆【補足情報】上下左右に50ピクセルの余白を設けてください")
    if costumes:
        lines.append(f"◆【補足情報】服装: {' / '.join(costumes)}")
    if extra_notes:
        for n in extra_notes:
            lines.append(f"◆【補足情報】{n}")
    return lines

