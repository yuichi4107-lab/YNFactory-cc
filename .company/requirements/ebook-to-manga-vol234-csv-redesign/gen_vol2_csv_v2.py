def hdr(*chars):
    lines = [
        "◆【注意】【】で囲まれた単語は感情や状況の指示であり、画像内に文字として描画しないでください",
        "◆【絶対最優先】必ずフルカラーにしてください",
        "◆【絶対最優先】必ず日本のアニメ・マンガ調のイラストで描いてください。実写風・フォトリアル風は禁止です。",
    ]
    for c in chars:
        lines.append(f"◆【絶対最優先】キャラクター外見: {c}")
    lines.append("◆【出力サイズ】2:3")
    lines.append("◆【補足情報】上下左右に50ピクセルの余白を設けてください")
    return "\n".join(lines)

def mk(page_num, tmpl, prompt, panels):
    return [str(page_num), tmpl, prompt, json.dumps(panels, ensure_ascii=False)]

def nar(pid, text):
    return {"panel_id": pid, "type": "narration", "speaker": None, "text": text}

def dlg(pid, speaker, text):
    return {"panel_id": pid, "type": "dialogue", "speaker": speaker, "text": text}

