def panel_count(template: str) -> int:
    if template == "テンプレ1":
        return 1
    if template in {"テンプレ2", "テンプレ3", "テンプレ4"}:
        return 2
    return 3


def make_text_json(template: str, lines: list[tuple[str, str]], narration: str) -> list[dict[str, object]]:
    n = panel_count(template)
    if n == 1:
        return [
            {"panel_id": 1, "type": "narration", "speaker": None, "text": narration},
            {"panel_id": 1, "type": "dialogue", "speaker": lines[0][0], "text": lines[0][1]},
            {"panel_id": 1, "type": "dialogue", "speaker": lines[1][0], "text": lines[1][1]},
        ]
    if n == 2:
        return [
            {"panel_id": 1, "type": "narration", "speaker": None, "text": narration},
            {"panel_id": 1, "type": "dialogue", "speaker": lines[0][0], "text": lines[0][1]},
            {"panel_id": 2, "type": "dialogue", "speaker": lines[1][0], "text": lines[1][1]},
        ]
    return [
        {"panel_id": 1, "type": "narration", "speaker": None, "text": narration},
        {"panel_id": 2, "type": "dialogue", "speaker": lines[0][0], "text": lines[0][1]},
        {"panel_id": 3, "type": "dialogue", "speaker": lines[1][0], "text": lines[1][1]},
    ]


