def renumber_text_row(row: dict[str, str], new_page: int) -> dict[str, str]:
    updated = dict(row)
    updated["ページ番号"] = str(new_page)
    if new_page == 100:
        updated["漫画作成のプロンプト"] = updated["漫画作成のプロンプト"].replace("発行日: 2026年6月4日", "発行日: 2026年6月5日")
    return updated


def main() -> None:
    rows = list(csv.DictReader(CSV_PATH.open(encoding="utf-8-sig")))
    base_rows = [dict(r) for r in rows if int(r["ページ番号"]) <= 53]
    text_tail = {int(r["ページ番号"]): dict(r) for r in rows if int(r["ページ番号"]) in {54, 55, 56}}

    if len(EXTRA_BEATS) != 44 or len(ADD_TEMPLATES) != 44:
        raise RuntimeError("extra page configuration must be 44 rows")

    expanded = list(base_rows)
    for page_num, template, beat in zip(range(54, 98), ADD_TEMPLATES, EXTRA_BEATS):
        prompt, text_json = make_prompt(page_num, template, beat)
        expanded.append(
            {
                "ページ番号": str(page_num),
                "使用するコマ割りテンプレ": template,
                "漫画作成のプロンプト": prompt,
                "コマ別テキストJSON": text_json,
                "outfit_id": "team_cafe",
            }
        )

    expanded.extend(
        [
            renumber_text_row(text_tail[54], 98),
            renumber_text_row(text_tail[55], 99),
            renumber_text_row(text_tail[56], 100),
        ]
    )

    with CSV_PATH.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["ページ番号", "使用するコマ割りテンプレ", "漫画作成のプロンプト", "コマ別テキストJSON", "outfit_id"],
        )
        writer.writeheader()
        writer.writerows(expanded)

    batch_dir = ROOT / "image_batches"
    batch_dir.mkdir(exist_ok=True)
    image_rows = [r for r in expanded if r["使用するコマ割りテンプレ"] != "テキストページ"]
    missing_rows = [r for r in image_rows if int(r["ページ番号"]) >= 54]
    for idx in range(0, len(missing_rows), 8):
        batch = missing_rows[idx : idx + 8]
        parts = [f"# Batch additional {idx // 8 + 1:03d}\n"]
        for row in batch:
            parts.append(f"## page_{int(row['ページ番号']):03d}\n")
            parts.append(row["漫画作成のプロンプト"])
            parts.append("")
        (batch_dir / f"batch_{8 + idx // 8:03d}.md").write_text("\n".join(parts), encoding="utf-8")

    progress_path = ROOT / "progress.json"
    progress = json.loads(progress_path.read_text(encoding="utf-8"))
    progress["target_pages"] = TARGET_PAGES
    progress["steps"]["5_images"]["status"] = "pending"
    progress["steps"]["5_images"]["completed"] = 52
    progress["steps"]["5_images"]["total"] = 96
    progress["steps"]["5_images"]["missing_pages"] = list(range(54, 98))
    progress["steps"]["7_epub"]["status"] = "pending"
    progress["steps"]["8_metadata"]["status"] = "pending"
    progress_path.write_text(json.dumps(progress, ensure_ascii=False, indent=2), encoding="utf-8")

