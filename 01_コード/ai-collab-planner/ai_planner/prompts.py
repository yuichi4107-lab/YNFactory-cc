def mediate_round(
    goal: str,
    issues_document: str,
    context_document: str,
    response_a: str,
    response_b: str,
    round_number: int,
    max_rounds: int,
) -> str:
    return f"""【工程】調停（ラウンド{round_number}／上限{max_rounds}）

あなたは中立の調停役です。両者の応答を読み、争点ごとに**両案の良いところを組み込んだ統合案**を作ってください。
{COMMON_PURPOSE}
<依頼>
{goal}
</依頼>

<初回の争点表>
{issues_document}
</初回の争点表>

<前のラウンドまでの経緯>
{context_document}
</前のラウンドまでの経緯>

<立場Aの応答>
{response_a}
</立場Aの応答>

<立場Bの応答>
{response_b}
</立場Bの応答>

## あなたの任務

勝者を決める役ではありません。**両案の良いところを1つにまとめる役**です。

各争点の状態を、次の3つから1つ選んでください。

- **統合済み** … 両者の良いところを組み込んだ結論が出た。
  この状態にするときは、`立場Aから採った要素` と `立場Bから採った要素` の**両方**を必ず埋めてください。
  片方しか書けないなら、それは統合ではなく選別です。まだ `未整理` のままにしてください。
  ただし、片方が明確に事実誤認をしていた場合に限り、他方のみを採用してよい。その場合は理由欄に事実誤認である旨を書く。
- **要判断** … 実在するトレードオフで、どちらを取るかは価値判断になる。人間が決めるべきもの。
  両者が揃って「両立しない」と述べ、その理由に説得力がある場合にこれを選びます。
  **この状態が残るのは失敗ではありません。** 人間へ渡すべき成果です。
  無理に折衷案をひねり出して両方を壊すくらいなら、`要判断` として残してください。
- **未整理** … まだ詰まっていない。次のラウンドで扱う。

## 継続の判断

- 状態が `未整理` の争点が1つもなければ `終了：統合完了` と書いてください（`要判断` が残っていても構いません）。
- 両者が前のラウンドと同じ主張を繰り返しており、新しい根拠が出ていない場合は `終了：停滞` と書いてください。
  もう1ラウンド回しても同じ結果になると判断したときも `終了：停滞` です。
- それ以外は `続行` と書いてください。

`## ここまでの経緯` は、次のラウンドへ渡す唯一の引き継ぎ資料です。
議論の全文は次へ渡らないため、必要な文脈をここに凝縮してください。ただし冗長にしないでください。

## 出力形式

次の見出しを一字一句変えず、同じ順序で使用してください。前置きやコードフェンスは不要です。

# 調停
## ここまでの経緯
## 争点ごとの統合案
## 未整理件数
## 継続判定

- `## 争点ごとの統合案` は次の列を持つ表にしてください。初回争点表のすべての争点IDを含めてください。

| 争点ID | 状態 | 統合案 | 立場Aから採った要素 | 立場Bから採った要素 | 要判断の場合に人間が決めること |

- `状態` の欄には `統合済み` `要判断` `未整理` のいずれかだけを書いてください。
- `## 未整理件数` には `未整理: N件` の形式で**数字を含む1行だけ**を書いてください。他の文を書かないでください。
- `## 継続判定` には `続行` `終了：統合完了` `終了：停滞` の**いずれか1語だけ**を書いてください。
  理由や補足をこの節に書かないでください。
{COMMON_SAFETY}
"""


