def extract_forks_and_stances(goal: str) -> str:
    return f"""【工程】分岐点抽出と立場設定

あなたは要件定義の準備担当です。まず対象フォルダの現状を読み取り専用で確認し、そのうえで
「依頼文だけでは決まらない分岐点」と、それを踏まえた2つの立場を設定してください。
{COMMON_PURPOSE}
<依頼>
{goal}
</依頼>

## 手順

1. 対象フォルダに既存資料やコードがあれば、必要な範囲だけ読み、事実として確認できたことを整理する。
2. 依頼文と事実を突き合わせ、**決めないと先へ進めない分岐点**だけを挙げる。
   - 依頼文にすでに答えが書いてあることは分岐点ではない。
   - 好みの問題や、後からいくらでも変えられることも分岐点ではない。
   - 各分岐について、選択肢を2つ以上示す。
   - **後から覆すときのコストが大きい順**に並べる（「重要度」ではなく「不可逆性」で並べる）。
3. 上位2〜3件の分岐点を骨格にして、2つの立場を設定する。

## 立場の作り方

立場A・立場Bは、勝負をさせるためのものではありません。
**組み合わせる価値のある素材を2種類つくるため**のものです。
両者が似た案を書くと、後で統合しても何も生まれません。

- 分岐点を機械的に左右へ割り振らない。ばらばらの選択を束ねると、矛盾した立場になる。
- それぞれを**一貫した1つの設計思想**として書く。
- 「優先するもの」だけでなく「捨てるもの」を必ず書く。捨てるものを書かないと差が出ない。
- どちらの立場も、それ単独で筋が通っていて擁護できるものにする。片方をわざと劣った案にしない。

## 分岐点がない場合

依頼文だけで実装方針が一意に決まり、議論する分岐点が存在しない場合は、
`## 分岐点` の本文を `なし` という語で書き始めてください。その場合でも立場A・立場Bの見出しは残し、
本文に `分岐点がないため設定しません` と書いてください。

## 出力形式

次の見出しを一字一句変えず、同じ順序で使用してください。前置きやコードフェンスは付けないでください。

# 分岐点と立場
## 確認した事実
## 分岐点
## 立場A
### 優先するもの
### 捨てるもの
## 立場B
### 優先するもの
### 捨てるもの
{COMMON_SAFETY}
"""


