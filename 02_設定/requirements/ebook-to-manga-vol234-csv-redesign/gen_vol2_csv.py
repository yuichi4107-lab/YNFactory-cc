# ============================================================
# セルフチェック
# ============================================================
with open(OUTPUT_PATH, encoding='utf-8') as f:
    reader = csv.DictReader(f)
    over_count = 0
    total_panels = 0
    rows_data = list(reader)

for row in rows_data:
    if row['使用するコマ割りテンプレ'] == 'テキストページ':
        continue
    json_str = row['コマ別テキストJSON']
    try:
        items = json.loads(json_str)
    except Exception as e:
        print(f"JSON parse error on page {row['ページ番号']}: {e}")
        continue
    panel_chars = {}
    for item in items:
        pid = item['panel_id']
        panel_chars.setdefault(pid, 0)
        panel_chars[pid] += len(item['text'])
    for pid, chars in panel_chars.items():
        total_panels += 1
        if chars > 30:
            over_count += 1
            print(f"OVER: page={row['ページ番号']} panel={pid} chars={chars}")

ratio = over_count / max(1, total_panels) * 100
print(f"\n=== セルフチェック結果 ===")
print(f"総コマ数: {total_panels}")
print(f"30字超過コマ数: {over_count}")
print(f"超過率: {ratio:.2f}%")
print(f"{'PASS (5%未満)' if ratio < 5 else 'FAIL (5%以上、修正必要)'}")

