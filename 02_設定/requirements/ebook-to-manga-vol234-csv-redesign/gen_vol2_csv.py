def make_row(page_num, template, prompt, panel_json_list):
    """CSVの1行を作成"""
    json_str = json.dumps(panel_json_list, ensure_ascii=False)
    return [str(page_num), template, prompt, json_str]


def std_header(chars_list, size="2:3"):
    """標準ヘッダー行を生成（登場キャラ情報のリストを受け取る）"""
    lines = [
        "◆【注意】【】で囲まれた単語は感情や状況の指示であり、画像内に文字として描画しないでください",
        "◆【絶対最優先】必ずフルカラーにしてください",
        "◆【絶対最優先】必ず日本のアニメ・マンガ調のイラストで描いてください。実写風・フォトリアル風は禁止です。",
    ]
    for c in chars_list:
        lines.append(f"◆【絶対最優先】キャラクター外見: {c}")
    lines.append(f"◆【出力サイズ】{size}")
    lines.append("◆【補足情報】上下左右に50ピクセルの余白を設けてください")
    return "\n".join(lines)


